const parse = (s) => { try { const a = JSON.parse(s || '[]'); return Array.isArray(a) ? a : []; } catch { return []; } };

/** Добавляет уроки в уже существующую базу один раз. */
export async function ensureLessons() {
  await run('CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)');
  if (await one(`SELECT 1 FROM meta WHERE key='lessons-v1'`)) return;
  for (const [title, lesson] of EXTRA) {
    const c = await one('SELECT id, items FROM courses WHERE title=?', title);
    if (!c) continue;
    const items = parse(c.items);
    if (items.some((x) => x.id === lesson.id)) continue;
    // в «Основах волонтёрства» путь заявки теперь другой: заявки приходят помощникам сами
    for (const it of items) if (it.kind === 'order') it.steps = it.steps.map((s) => (s === 'Координатор назначает помощника' ? 'Заявка приходит помощникам района' : s));
    await run('UPDATE courses SET items=? WHERE id=?', JSON.stringify([lesson, ...items]), c.id);
  }
  if (!(await one('SELECT id FROM courses WHERE title=?', NEW_COURSE.title)))
    await run('INSERT INTO courses (title,descr,icon,color,items,created_at) VALUES (?,?,?,?,?,?)', NEW_COURSE.title, NEW_COURSE.descr, NEW_COURSE.icon, NEW_COURSE.color, JSON.stringify(NEW_COURSE.items), Date.now());
  await run(`INSERT INTO meta (key,value) VALUES ('lessons-v1', ?)`, String(Date.now()));
}
